const EMAIL = "ibraheem.ha2@hotmail.com";
const PHONE_DISPLAY = "+962 792939802";
const PHONE_E164 = "962792939802";
const WHATSAPP = `https://wa.me/${PHONE_E164}`;

function applyLang(lang) {
  const t = i18n[lang] || i18n.en;
  document.documentElement.lang = t.lang;
  document.documentElement.dir = t.dir;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (t[key] != null) el.textContent = t[key];
  });
  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
  localStorage.setItem("ibra_lang", lang);
}

function initLang() {
  const saved = localStorage.getItem("ibra_lang");
  const start = saved === "ar" || saved === "en" ? saved : "en";
  applyLang(start);
  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.addEventListener("click", () => applyLang(btn.dataset.lang));
  });
}

function initNav() {
  const btn = document.querySelector(".menu-btn");
  const links = document.querySelector(".nav-links");
  if (!btn || !links) return;
  btn.addEventListener("click", () => links.classList.toggle("open"));
  links.querySelectorAll("a").forEach((a) => {
    a.addEventListener("click", () => links.classList.remove("open"));
  });
}

function initFilters() {
  const buttons = document.querySelectorAll(".filter-btn");
  const cards = document.querySelectorAll(".template-card");
  buttons.forEach((btn) => {
    btn.addEventListener("click", () => {
      buttons.forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");
      const f = btn.dataset.filter;
      cards.forEach((card) => {
        const show = f === "all" || card.dataset.category === f;
        card.style.display = show ? "" : "none";
      });
    });
  });
}

function initForm() {
  const form = document.getElementById("contact-form");
  if (!form) return;
  form.addEventListener("submit", (e) => {
    e.preventDefault();
    const name = form.name.value.trim();
    const email = form.email.value.trim();
    const type = form.type.value;
    const message = form.message.value.trim();
    const subject = encodeURIComponent(`Ibra Studio request — ${type}`);
    const body = encodeURIComponent(
      `Name: ${name}\nEmail: ${email}\nProject: ${type}\n\n${message}`
    );
    window.location.href = `mailto:${EMAIL}?subject=${subject}&body=${body}`;
  });
}

function initContactLinks() {
  document.querySelectorAll("[data-whatsapp]").forEach((el) => {
    el.setAttribute("href", WHATSAPP);
    el.setAttribute("target", "_blank");
    el.setAttribute("rel", "noopener");
  });
  document.querySelectorAll("[data-email-link]").forEach((el) => {
    el.setAttribute("href", `mailto:${EMAIL}`);
    el.textContent = EMAIL;
  });
  document.querySelectorAll("[data-phone]").forEach((el) => {
    el.textContent = PHONE_DISPLAY;
    if (el.tagName === "A") el.setAttribute("href", `tel:+${PHONE_E164}`);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initLang();
  initNav();
  initFilters();
  initForm();
  initContactLinks();
});
