function renderCatalog(lang) {
  const grid = document.getElementById("templates-grid");
  if (!grid || !window.IBRA_CATALOG) return;
  const t = i18n[lang] || i18n.en;
  grid.innerHTML = window.IBRA_CATALOG.map((item) => {
    const loc = item[lang] || item.en;
    const tags = (item.tags || [])
      .map((tag) => `<span class="tag">${tag}</span>`)
      .join("");
    const bg = item.color || "linear-gradient(145deg,#222,#444)";
    const accent = item.accent || "#3dffa8";
    var previewSrcs = getPreviews(item.thumb);
    var heroImg = item.thumb ? '<img class="thumb-img thumb-preview" src="'+item.thumb+'" alt="" loading="lazy" />' : "";
    var extraPreviews = previewSrcs.map(function(s){return '<img class="thumb-preview thumb-extra" src="'+s+'" alt="" loading="lazy" />'}).join("");
    return `
      <article class="template-card" data-category="${item.category}" data-featured="${item.featured ? "1" : "0"}">
        <a class="template-preview" href="${item.path}" target="_blank" rel="noopener" style="--thumb:${bg};--thumb-accent:${accent}" aria-label="${loc.title}">
          ${heroImg}${extraPreviews}
          <span class="thumb-ui">
            <span class="thumb-dot"></span><span class="thumb-dot"></span><span class="thumb-dot"></span>
          </span>
          <span class="thumb-title">${loc.title}</span>
        </a>
        <div class="template-body">
          <div class="template-tags">${tags}</div>
          <h3>${loc.title}</h3>
          <p>${loc.text}</p>
          <div class="template-actions">
            <a class="btn btn-ghost btn-sm" href="${item.path}" target="_blank" rel="noopener">${t.preview}</a>
            <a class="btn btn-primary btn-sm" href="#contact">${t.want_this}</a>
          </div>
        </div>
      </article>`;
  }).join("");
  applyFilter(currentFilter);
  document.querySelectorAll(".template-card").forEach(initHoverPreview);
}

function applyFilter(f) {
  currentFilter = f || "featured";
  document.querySelectorAll(".template-card").forEach((card) => {
    let show = false;
    if (currentFilter === "all") show = true;
    else if (currentFilter === "featured") show = card.dataset.featured === "1";
    else show = card.dataset.category === currentFilter;
    card.style.display = show ? "" : "none";
  });
}

function initNav() {
  const btn = document.querySelector(".menu-btn");
  const links = document.querySelector(".nav-links");
  if (!btn || !links) return;
  btn.addEventListener("click", () => links.classList.toggle("open"));
  links.querySelectorAll("a").forEach((a) => {
    a.addEventListener("click", () => links.classList.remove("open"));
  });
}

function initFilters() {
  const buttons = document.querySelectorAll(".filter-btn");
  buttons.forEach((btn) => {
    btn.addEventListener("click", () => {
      buttons.forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");
      applyFilter(btn.dataset.filter || "featured");
    });
  });
  const active = document.querySelector(".filter-btn.active");
  applyFilter(active ? active.dataset.filter : "featured");
}

function initForm() {
  const form = document.getElementById("contact-form");
  if (!form) return;
  form.addEventListener("submit", (e) => {
    e.preventDefault();
    const name = form.name.value.trim();
    const email = form.email.value.trim();
    const type = form.type.value;
    const message = form.message.value.trim();
    const subject = encodeURIComponent(`Ibra Studio request — ${type}`);
    const body = encodeURIComponent(
      `Name: ${name}\nEmail: ${email}\nProject: ${type}\n\n${message}`
    );
    window.location.href = `mailto:${EMAIL}?subject=${subject}&body=${body}`;
  });
}

function initContactLinks() {
  document.querySelectorAll("[data-whatsapp]").forEach((el) => {
    el.setAttribute("href", WHATSAPP);
    el.setAttribute("target", "_blank");
    el.setAttribute("rel", "noopener");
  });
  document.querySelectorAll("[data-email-link]").forEach((el) => {
    el.setAttribute("href", `mailto:${EMAIL}`);
    el.textContent = EMAIL;
  });
  document.querySelectorAll("[data-phone]").forEach((el) => {
    el.textContent = PHONE_DISPLAY;
    if (el.tagName === "A") el.setAttribute("href", `tel:+${PHONE_E164}`);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initLang();
  initNav();
  initFilters();
  initForm();
  initContactLinks();
});
